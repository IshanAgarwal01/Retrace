"""Database access for both places Retrace runs.

Hosted, DATABASE_URL points at a Postgres database (Neon's free tier). On a laptop
and in tests there is no DATABASE_URL, so a local SQLite file is used instead.
The rest of the code only sees the small Database class below, so it doesn't
care which one it's talking to.
"""

import os
import sqlite3
from contextlib import contextmanager
from pathlib import Path

DB_PATH = Path(os.environ.get("RETRACE_DB_PATH", Path(__file__).parent / "retrace.db"))

# {id} becomes the auto-numbering primary key, which the two databases spell differently
SCHEMA = """
CREATE TABLE IF NOT EXISTS assignments (
    id           {id},
    canvas_uid   TEXT NOT NULL UNIQUE,
    course       TEXT,
    course_code  TEXT,
    title        TEXT NOT NULL,
    due_at       TEXT,
    all_day      INTEGER NOT NULL DEFAULT 0,
    url          TEXT,
    last_seen_at TEXT NOT NULL,
    done_at      TEXT
);

CREATE TABLE IF NOT EXISTS assignment_changes (
    id            {id},
    assignment_id INTEGER NOT NULL REFERENCES assignments(id),
    field         TEXT NOT NULL,
    old_value     TEXT,
    new_value     TEXT,
    detected_at   TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS items (
    id         {id},
    type       TEXT NOT NULL,
    title      TEXT NOT NULL,
    source     TEXT NOT NULL,
    status     TEXT NOT NULL DEFAULT 'open',
    due_at     TEXT,
    all_day    INTEGER NOT NULL DEFAULT 0,
    course     TEXT,
    place      TEXT,
    raw_text   TEXT NOT NULL,
    ai_output  TEXT,
    created_at TEXT NOT NULL,
    done_at    TEXT
)
"""

ID_COLUMN = {
    "sqlite": "INTEGER PRIMARY KEY",
    "postgres": "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
}

# Columns added after a table was first created. CREATE TABLE IF NOT EXISTS skips
# tables that already exist, so older databases get these with ALTER TABLE instead.
ADDED_COLUMNS = [
    ("assignments", "done_at", "TEXT"),
]


class Database:
    """One open connection. Rows always come back as plain dicts."""

    def __init__(self, raw, dialect: str):
        self.raw = raw
        self.dialect = dialect

    def execute(self, sql: str, params: tuple | list = ()):
        if self.dialect == "postgres":
            # Postgres drivers use %s where SQLite uses ?. Our SQL never contains a
            # literal ? or %, so a plain swap is safe.
            sql = sql.replace("?", "%s")
        return self.raw.execute(sql, params)

    @contextmanager
    def transaction(self):
        """Everything inside saves together, or (on an error) not at all."""
        try:
            yield
            self.raw.commit()
        except BaseException:
            self.raw.rollback()
            raise

    def close(self) -> None:
        self.raw.close()


def connect() -> Database:
    url = os.environ.get("DATABASE_URL")
    if url:
        import psycopg
        from psycopg.rows import dict_row

        return Database(psycopg.connect(url, row_factory=dict_row), "postgres")

    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    raw = sqlite3.connect(DB_PATH)
    raw.row_factory = lambda cursor, row: {col[0]: value for col, value in zip(cursor.description, row)}
    raw.execute("PRAGMA foreign_keys = ON")
    return Database(raw, "sqlite")


def existing_columns(db: Database, table: str) -> set[str]:
    if db.dialect == "postgres":
        rows = db.execute(
            "SELECT column_name AS name FROM information_schema.columns WHERE table_name = ?",
            (table,),
        )
    else:
        # Safe to format: table names come from ADDED_COLUMNS, never from users
        rows = db.execute(f"PRAGMA table_info({table})")
    return {row["name"] for row in rows.fetchall()}


def init_db() -> None:
    db = connect()
    try:
        with db.transaction():
            for statement in SCHEMA.format(id=ID_COLUMN[db.dialect]).split(";"):
                db.execute(statement)
            for table, column, column_type in ADDED_COLUMNS:
                if column not in existing_columns(db, table):
                    db.execute(f"ALTER TABLE {table} ADD COLUMN {column} {column_type}")
    finally:
        db.close()
